#!/usr/bin/env python3
"""tools/levels.txt -> assets/floes.bin (floeslide.zar: every floe's cells, one floe read when it loads) and
src/levels.c (the floe table, world names, bot solutions). Every floe is solved with floe.py's BFS: the fewest moves
become its par, and that solution is what the autopilot build plays.
Cells are packed two per byte (low nibble first), codes as in floe.py / game.h."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import floe as F  # noqa: E402

floes = F.parse(open(os.path.join(HERE, 'levels.txt')).read())
worlds = []
for w, _ in floes:
    if w not in worlds:
        worlds.append(w)
out = ['/* Generated by tools/make_levels.py from tools/levels.txt, do not edit. The cells are assets/floes.bin. */',
       '#include "game.h"', '']
data = []
rows = []
sols = []
for n, (world, fl) in enumerate(floes):
    assert fl.w <= 20 and fl.h <= 12, (n, fl.w, fl.h)
    sol, states = fl.solve()
    assert sol, ('unsolvable', n + 1)
    assert fl.fish <= 9
    off = len(data)
    cells = list(fl.cells) + ([0] if len(fl.cells) % 2 else [])
    for i in range(0, len(cells), 2):
        data.append(cells[i] | (cells[i + 1] << 4))
    rows.append('    { %4d, %2d, %2d, %3d, %d, %2d, %d },   /* %d-%d par %d, %d states */' % (
        off, fl.w, fl.h, fl.start, fl.fish, len(sol), worlds.index(world),
        worlds.index(world) + 1, sum(1 for ww, _ in floes[:n] if ww == world) + 1, len(sol), states))
    sols.append(sol)
    print('%2d %-16s par %2d states %6d %s' % (n + 1, world, len(sol), states, sol))
with open(os.path.join(ROOT, 'assets', 'floes.bin'), 'wb') as f:
    f.write(bytes(data))
out.append('const floe_t FLOES[FLOE_COUNT] = {')
out += rows
out.append('};')
out.append('')
out.append('const char * const WORLD_NAMES[WORLD_COUNT] = {')
out += ['    "%s",' % w for w in worlds]
out.append('};')
out.append('')
out.append('#ifdef AUTOPILOT')
out.append('const char * const SOLUTIONS[FLOE_COUNT] = {')
out += ['    "%s",' % s for s in sols]
out.append('};')
out.append('#endif')
with open(os.path.join(ROOT, 'src', 'levels.c'), 'w') as f:
    f.write('\n'.join(out) + '\n')
with open(os.path.join(ROOT, 'src', 'levels.h'), 'w') as f:
    f.write('/* Generated by tools/make_levels.py, do not edit */\n#define FLOE_COUNT  %d\n#define WORLD_COUNT %d\n#define FLOES_PER_WORLD %d\n' % (len(floes), len(worlds), len(floes) // len(worlds)))
print(len(data), 'bytes of floe data in assets/floes.bin')
